#!/usr/bin/env python3
"""Run `klt erc` (supply + well/substrate-tie checks) on every generated cell.

Usage: run_erc.py --config CONFIG.json [--spec SPEC.json] [--gds DIR] [--out DIR] [--check]

For each cell in CONFIG the runner runs `klt erc` with the shared supply spec
(default: <config dir>/erc-spec.json -- stackup GatPoly/Cont/Metal1, VDD and
VSS declared `"kind": "supply"`, and the two tap ties layout/gen_layouts.py
draws) and the curated `sg13g2` deck (the same one `klt lvs` extracts with in
layout/run_lvs.py -- it declares the PDK family's substrate-isolation layer,
so the substrate-continuity half of the supply check is evaluated instead of
disclosed `substrate_isolation_undecidable`, which `klt signoff` refuses to
grade item 11 on) on <gds>/<cell>.gds, writing <out>/<cell>.json.

It also runs every negative-control stream under <out>/controls/*.gds
(regenerated by `layout/gen_controls.py`, issue #179: a cell with its n-well
tap band removed) against the same spec, writing <out>/controls/<stem>.json.
A control is graded the opposite way: its report MUST show `erc.missing_tie`
-- the falsifiable half that proves the spec can fail.

Defaults: --gds <config dir>/gds, --out <config dir>/erc. Paths are given to
klt relative to the current directory, so run from the repo root.

`klt erc` exits 4 on any run without --pdk (the antenna half is `not_checked`
even when the connectivity half is clean), so the runner gates on each
report's `erc_status`, never the exit code.

`--check` runs `klt erc --check` (cheap mode: re-hash the layout and spec
recorded in each report) on every cell and control report and fails on
stale/missing/stray reports, or on a control report that no longer shows
`erc.missing_tie`.

Exit codes: 0 every cell clean (erc_status `clean`, one island per supply,
zero findings, no skipped tie) and every control failing as designed;
1 tooling error (klt missing a command in layout/toolchain.json, klt failed,
no control streams on disk) or `--check` drift; 2 invalid config; 4 reports
written but a verdict is wrong (the reports are the evidence; nothing is
hidden or retried).
"""
import hashlib
import json
import os
import pathlib
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import toolchain_pin  # noqa: E402

DECK = toolchain_pin.DECK
# The shared pin in layout/toolchain.json is deliberately untouched by #179, but
# its commit predates the `well_complement_of` tie schema erc-spec.json uses:
# that build advertises `erc` and then rejects the spec. The reports were
# produced by this build, so it is the install for this runner.
ERC_INSTALL = ("git+https://github.com/2AMLogic/klayout-tools@"
               "db1e2f17146dc834ec4aab351ef9ffd8c716d36c")
SCHEMA_HINT = ("the spec's substrate tie uses `well_complement_of` with a null `well_layer`; "
               "klt builds older than the ERC-capable one demand `well_boxes` instead. "
               "Install a compatible build: uv tool install --force " + ERC_INSTALL
               + " (or run `uvx --from " + ERC_INSTALL + " klt ...`)")
ERC_EXIT_OK = (0, 3, 4)  # 3 violations / 4 antenna not_checked: report still written

relpath = toolchain_pin.relpath


def build_command(layout, spec, top):
    """The `klt erc` argv for one stream (pure; paths relative to cwd)."""
    cmd = ["klt", "erc", relpath(layout), relpath(spec), "--deck", DECK, "--format", "json"]
    return cmd + ["--top", top] if top else cmd


cell_names = toolchain_pin.cell_names


def supply_names(config):
    """[vdd_net, vss_net] the generated cells draw as their rails."""
    proc = toolchain_pin.load_json(config)["process"]
    return [proc["vdd_net"], proc["vss_net"]]


def missing_ties(report):
    return [f for f in report.get("erc_findings", []) if f.get("rule") == "erc.missing_tie"]


def degenerate_ties(report):
    """Skipped erc.missing_tie work: a tie the run could not grade."""
    return [s for s in report.get("erc_coverage", {}).get("skipped", [])
            if s.get("id") == "erc.missing_tie"]


def supply_islands(report):
    """[(net, matched, expected)] per declared supply, in spec order."""
    return [(n["name"], n["matched_islands"], n["expected_islands"]) for n in report.get("nets", [])]


def tie_check_ids(spec):
    return [f'erc.missing_tie:["{t["name"]}"]' for t in spec.get("ties", [])]


def spec_problems(spec, supplies):
    """Reasons the spec cannot grade both configured rails (empty = usable).

    `supplies` is [vdd_net, vss_net] from the config: the spec must declare
    exactly those as supplies and tie each one to its well/substrate."""
    bad = []
    declared = [n["name"] for n in spec.get("nets", []) if n.get("kind") == "supply"]
    if sorted(declared) != sorted(supplies):
        bad.append(f"spec supplies {declared} != configured rails {list(supplies)}")
    tied = {t.get("net") for t in spec.get("ties", [])}
    for net in supplies:
        if net not in tied:
            bad.append(f"spec has no tie to supply {net}")
    return bad


def cell_ok(report, supplies=None, spec=None):
    """erc_status clean, one island per supply, zero findings, no skipped tie.

    With `supplies` the report must name exactly those rails, one island each;
    with `spec` every tie it declares must be in the report's checked set."""
    if not (report.get("erc_status") == "clean"
            and report.get("erc_finding_count") == 0
            and all(m == e for _, m, e in supply_islands(report))
            and not degenerate_ties(report)):
        return False
    if supplies is not None:
        isl = supply_islands(report)
        if sorted(n for n, _, _ in isl) != sorted(supplies) or any(m != 1 for _, m, _ in isl):
            return False
    if spec is not None:
        checked = set(report.get("erc_coverage", {}).get("checked", []))
        if not set(tie_check_ids(spec)) <= checked:
            return False
    return True


def control_ok(report):
    """The negative direction: a control stream MUST show erc.missing_tie."""
    return bool(missing_ties(report))


def summarize(what, report):
    return "{}: erc_status={} findings={} islands={}".format(
        what, report.get("erc_status"), report.get("erc_finding_count"),
        "/".join(f"{n}={m}" for n, m, _ in supply_islands(report)))


def run_klt_erc(cmd, report_path):
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode not in ERC_EXIT_OK:
        print(f"run_erc: klt erc failed (exit {r.returncode}):\n{r.stdout}{r.stderr}",
              file=sys.stderr)
        if "well_boxes" in r.stdout + r.stderr:
            print(f"run_erc: {SCHEMA_HINT}", file=sys.stderr)
        return None
    try:
        report = json.loads(r.stdout)
    except ValueError:
        print(f"run_erc: klt erc wrote no JSON report:\n{r.stdout}{r.stderr}", file=sys.stderr)
        return None
    report_path.write_text(r.stdout if r.stdout.endswith("\n") else r.stdout + "\n")
    return report


def controls(out):
    """Negative-control streams under <out>/controls: [(stem, gds_path)]."""
    cdir = pathlib.Path(out) / "controls"
    return sorted((p.stem, p) for p in cdir.glob("*.gds")) if cdir.is_dir() else []


def sha(path):
    return "sha256:" + hashlib.sha256(pathlib.Path(path).read_bytes()).hexdigest()


def binding_problems(report, layout, spec):
    """The report must describe the layout and spec the caller asked for.

    `klt erc --check` only rehashes whatever paths the report embeds, so a
    report copied over another cell's (or one run with a different spec) is
    fresh against itself; compare against the requested inputs instead."""
    bad = []
    rp = report.get("file", {}).get("path")
    if rp is None or os.path.normpath(rp) != os.path.normpath(relpath(layout)):
        bad.append(f"report names layout {rp}, expected {relpath(layout)}")
    if os.path.normpath(str(report.get("spec"))) != os.path.normpath(relpath(spec)):
        bad.append(f"report names spec {report.get('spec')}, expected {relpath(spec)}")
    prov = report.get("provenance", {})
    if not pathlib.Path(layout).exists():
        bad.append(f"layout {layout} missing")
    elif prov.get("input", {}).get("content_hash") != sha(layout):
        bad.append(f"report layout hash does not match {relpath(layout)}")
    if prov.get("spec", {}).get("content_hash") != sha(spec):
        bad.append(f"report spec hash does not match {relpath(spec)}")
    return bad


def check_report(report_path):
    return subprocess.run(["klt", "erc", "--check", str(report_path)],
                          capture_output=True, text=True)


def do_check(cells, out, spec, gds, supplies, spec_doc=None):
    bad = []
    spec_doc = toolchain_pin.load_json(spec) if spec_doc is None else spec_doc
    ctl = controls(out)
    streams = [(c, pathlib.Path(out) / f"{c}.json", pathlib.Path(gds) / f"{c}.gds")
               for c in cells]
    streams += [(f"control {s}", pathlib.Path(out) / "controls" / f"{s}.json", g)
                for s, g in ctl]
    if not ctl:
        bad.append(f"no negative-control streams in {pathlib.Path(out) / 'controls'}; "
                   "regenerate with layout/gen_controls.py")
    for what, rep, layout in streams:
        problems = toolchain_pin.check_report_fresh(what, rep, "erc", check_report)
        bad += problems
        if problems:
            continue
        doc = json.loads(rep.read_text())
        bad += [f"{what}: {b}" for b in binding_problems(doc, layout, spec)]
        if what.startswith("control"):
            if not control_ok(doc):
                bad.append(f"{what}: report no longer shows erc.missing_tie")
        elif not cell_ok(doc, supplies, spec_doc):
            bad.append(f"{summarize(what, doc)}: not a clean supply/tie verdict")
    bad += toolchain_pin.stray_reports(out, cells)
    bad += toolchain_pin.stray_reports(pathlib.Path(out) / "controls", {s for s, _ in ctl},
                                       "stray control report")
    return toolchain_pin.emit_check_errors(bad)


def main(argv=None):
    a, cfgdir, gds, out = toolchain_pin.parse_runner_args(__doc__, "erc", argv,
                                                          extra_flags=("--spec",))
    spec = pathlib.Path(a.spec) if a.spec else cfgdir / "erc-spec.json"
    try:
        config = toolchain_pin.load_json(a.config)
        cells = cell_names(config)
        supplies = supply_names(config)
    except (OSError, ValueError, KeyError) as e:
        print(f"run_erc: invalid config: {e}", file=sys.stderr)
        return 2
    if not spec.exists():
        print(f"run_erc: spec {spec} missing", file=sys.stderr)
        return 2
    try:
        spec_doc = json.loads(spec.read_text())
    except ValueError as e:
        print(f"run_erc: invalid spec {spec}: {e}", file=sys.stderr)
        return 2
    problems = spec_problems(spec_doc, supplies)
    if problems:
        print("run_erc: invalid spec: " + "; ".join(problems), file=sys.stderr)
        return 2
    preflight = toolchain_pin.ensure_commands(
        "run_erc", "install a build with `erc` and the tie schema erc-spec.json uses: "
        + ERC_INSTALL)
    if preflight:
        return preflight
    if a.check:
        return do_check(cells, out, spec, gds, supplies, spec_doc)
    ctl = controls(out)
    if not ctl:
        print(f"run_erc: no negative-control streams in {out / 'controls'}; "
              "regenerate with layout/gen_controls.py", file=sys.stderr)
        return 1
    out.mkdir(parents=True, exist_ok=True)
    (out / "controls").mkdir(parents=True, exist_ok=True)
    worst = 0
    for cell in cells:
        rep = out / f"{cell}.json"
        report = run_klt_erc(build_command(gds / f"{cell}.gds", spec, cell), rep)
        if report is None:
            return 1
        print(summarize(cell, report))
        if not cell_ok(report, supplies, spec_doc):
            worst = 4
    for stem, gds_path in ctl:
        rep = out / "controls" / f"{stem}.json"
        report = run_klt_erc(build_command(gds_path, spec, None), rep)
        if report is None:
            return 1
        print(summarize(f"control {stem}", report)
              + f" missing_tie={len(missing_ties(report))}")
        if not control_ok(report):
            print(f"run_erc: control {stem} does not show erc.missing_tie", file=sys.stderr)
            worst = 4
    return worst


if __name__ == "__main__":
    sys.exit(main())
