#!/usr/bin/env python3
"""Run `klt erc` (supply + well/substrate-tie checks) on every generated cell.

Usage: run_erc.py --config CONFIG.json [--spec SPEC.json] [--gds DIR] [--out DIR] [--check]

For each cell in CONFIG the runner runs `klt erc` with the shared supply spec
(default: <config dir>/erc-spec.json -- stackup GatPoly/Cont/Metal1, VDD and
VSS declared `"kind": "supply"`, and the two tap ties layout/gen_layouts.py
draws) and the curated `sg13g2` deck (the same one `klt lvs` extracts with in
layout/run_lvs.py -- it declares the PDK family's substrate-isolation layer,
so the substrate-continuity half of the supply check is evaluated instead of
disclosed `substrate_isolation_undecidable`, which `klt signoff` refuses to
grade item 11 on) on <gds>/<cell>.gds, writing <out>/<cell>.json.

It also runs every negative-control stream under <out>/controls/*.gds
(regenerated by `layout/gen_controls.py`, issue #179: a cell with its n-well
tap band removed) against the same spec, writing <out>/controls/<stem>.json.
A control is graded the opposite way: its report MUST show `erc.missing_tie`
-- the falsifiable half that proves the spec can fail.

Defaults: --gds <config dir>/gds, --out <config dir>/erc. Paths are given to
klt relative to the current directory, so run from the repo root.

`klt erc` exits 4 on any run without --pdk (the antenna half is `not_checked`
even when the connectivity half is clean), so the runner gates on each
report's `erc_status`, never the exit code.

`--check` runs `klt erc --check` (cheap mode: re-hash the layout and spec
recorded in each report) on every cell and control report and fails on
stale/missing/stray reports, or on a control report that no longer shows
`erc.missing_tie`.

Exit codes: 0 every cell clean (erc_status `clean`, one island per supply,
zero findings, no skipped tie) and every control failing as designed;
1 tooling error (klt missing a command in layout/toolchain.json, klt failed,
no control streams on disk) or `--check` drift; 2 invalid config; 4 reports
written but a verdict is wrong (the reports are the evidence; nothing is
hidden or retried).
"""
import argparse
import json
import os
import pathlib
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import toolchain_pin  # noqa: E402

DECK = "sg13g2"
ERC_EXIT_OK = (0, 3, 4)  # 3 violations / 4 antenna not_checked: report still written


def relpath(p):
    return os.path.relpath(p)


def build_command(layout, spec, top):
    """The `klt erc` argv for one stream (pure; paths relative to cwd)."""
    cmd = ["klt", "erc", relpath(layout), relpath(spec), "--deck", DECK, "--format", "json"]
    return cmd + ["--top", top] if top else cmd


def cell_names(config_path):
    return [c["name"] for c in json.loads(pathlib.Path(config_path).read_text())["cells"]]


def missing_ties(report):
    return [f for f in report.get("erc_findings", []) if f.get("rule") == "erc.missing_tie"]


def degenerate_ties(report):
    """Skipped erc.missing_tie work: a tie the run could not grade."""
    return [s for s in report.get("erc_coverage", {}).get("skipped", [])
            if s.get("id") == "erc.missing_tie"]


def supply_islands(report):
    """[(net, matched, expected)] per declared supply, in spec order."""
    return [(n["name"], n["matched_islands"], n["expected_islands"]) for n in report.get("nets", [])]


def cell_ok(report):
    """erc_status clean, one island per supply, zero findings, no skipped tie."""
    return (report.get("erc_status") == "clean"
            and report.get("erc_finding_count") == 0
            and all(m == e for _, m, e in supply_islands(report))
            and not degenerate_ties(report))


def control_ok(report):
    """The negative direction: a control stream MUST show erc.missing_tie."""
    return bool(missing_ties(report))


def summarize(what, report):
    return "{}: erc_status={} findings={} islands={}".format(
        what, report.get("erc_status"), report.get("erc_finding_count"),
        "/".join(f"{n}={m}" for n, m, _ in supply_islands(report)))


def run_klt_erc(cmd, report_path):
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode not in ERC_EXIT_OK:
        print(f"run_erc: klt erc failed (exit {r.returncode}):\n{r.stdout}{r.stderr}",
              file=sys.stderr)
        return None
    try:
        report = json.loads(r.stdout)
    except ValueError:
        print(f"run_erc: klt erc wrote no JSON report:\n{r.stdout}{r.stderr}", file=sys.stderr)
        return None
    report_path.write_text(r.stdout if r.stdout.endswith("\n") else r.stdout + "\n")
    return report


def controls(out):
    """Negative-control streams under <out>/controls: [(stem, gds_path)]."""
    cdir = pathlib.Path(out) / "controls"
    return sorted((p.stem, p) for p in cdir.glob("*.gds")) if cdir.is_dir() else []


def do_check(cells, out, spec):
    bad = []
    streams = [(c, pathlib.Path(out) / f"{c}.json") for c in cells]
    streams += [(f"control {s}", pathlib.Path(out) / "controls" / f"{s}.json")
                for s, _ in controls(out)]
    if len(streams) == len(cells):
        bad.append(f"no negative-control streams in {pathlib.Path(out) / 'controls'}; "
                   "regenerate with layout/gen_controls.py")
    for what, rep in streams:
        if not rep.exists():
            bad.append(f"{what}: report {rep} missing")
            continue
        c = subprocess.run(["klt", "erc", "--check", str(rep)], capture_output=True, text=True)
        if c.returncode != 0:
            bad.append(f"{what}: klt erc --check exit {c.returncode}: {c.stdout.strip()[:200]}")
        elif what.startswith("control") and not control_ok(json.loads(rep.read_text())):
            bad.append(f"{what}: report no longer shows erc.missing_tie")
    stray = sorted(p.name for p in pathlib.Path(out).glob("*.json") if p.stem not in cells)
    bad += [f"stray report {s}" for s in stray]
    for b in bad:
        print(b, file=sys.stderr)
    return 1 if bad else 0


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--config", required=True)
    ap.add_argument("--spec")
    ap.add_argument("--gds")
    ap.add_argument("--out")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    cfgdir = pathlib.Path(a.config).resolve().parent
    spec = pathlib.Path(a.spec) if a.spec else cfgdir / "erc-spec.json"
    gds = pathlib.Path(a.gds) if a.gds else cfgdir / "gds"
    out = pathlib.Path(a.out) if a.out else cfgdir / "erc"
    try:
        cells = cell_names(a.config)
    except (OSError, ValueError, KeyError) as e:
        print(f"run_erc: invalid config: {e}", file=sys.stderr)
        return 2
    if not spec.exists():
        print(f"run_erc: spec {spec} missing", file=sys.stderr)
        return 2
    try:
        missing = toolchain_pin.check_commands()
    except (OSError, subprocess.CalledProcessError) as e:
        print(f"run_erc: cannot run klt: {e}", file=sys.stderr)
        return 1
    if missing:
        print(f"run_erc: klt lacks {missing}; install: {toolchain_pin.install_hint()}",
              file=sys.stderr)
        return 1
    if a.check:
        return do_check(cells, out, spec)
    ctl = controls(out)
    if not ctl:
        print(f"run_erc: no negative-control streams in {out / 'controls'}; "
              "regenerate with layout/gen_controls.py", file=sys.stderr)
        return 1
    out.mkdir(parents=True, exist_ok=True)
    (out / "controls").mkdir(parents=True, exist_ok=True)
    worst = 0
    for cell in cells:
        rep = out / f"{cell}.json"
        report = run_klt_erc(build_command(gds / f"{cell}.gds", spec, cell), rep)
        if report is None:
            return 1
        print(summarize(cell, report))
        if not cell_ok(report):
            worst = 4
    for stem, gds_path in ctl:
        rep = out / "controls" / f"{stem}.json"
        report = run_klt_erc(build_command(gds_path, spec, None), rep)
        if report is None:
            return 1
        print(summarize(f"control {stem}", report)
              + f" missing_tie={len(missing_ties(report))}")
        if not control_ok(report):
            print(f"run_erc: control {stem} does not show erc.missing_tie", file=sys.stderr)
            worst = 4
    return worst


if __name__ == "__main__":
    sys.exit(main())
